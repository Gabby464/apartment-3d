const TYPE = { switch: 'Ключ', socket: 'Контакт', light: 'Осветление', sensor: 'Датчик', intercom: 'Домофон', water: 'Вода/канал', fan: 'Вентилатор' };
const ROOMS = ['Спалня', 'Дрешник', 'Антре', 'Баня', 'Дневна', 'Кухня', 'Спалня 1'];
const ROOM_NAME = { Спалня: 'Родителска спалня' };
const VARIANT = { A: 'само при хол вариант А', B: 'само при хол вариант Б' };

const store = {
  get(k) { try { return localStorage.getItem('apt3-chg-' + k) === '1'; } catch { return false; } },
  set(k, v) { try { localStorage.setItem('apt3-chg-' + k, v ? '1' : '0'); } catch { /* storage unavailable */ } },
};
const esc = (s) => String(s).replace(/[&<>"]/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' }[c]));
const check = (key) => `<input type="checkbox" class="done" data-key="${key}" ${store.get(key) ? 'checked' : ''} aria-label="Договорено">`;

const main = document.getElementById('content');
const toc = document.getElementById('toc');
let html = '';
for (const sec of SECTIONS) {
  html += `<section id="${sec.id}"><h2>${sec.title}</h2><ol class="items">`;
  for (const it of sec.items) {
    html += `<li class="${store.get(it.id) ? 'is-done' : ''}">${check(it.id)}<div><p>${esc(it.t)}</p>${it.n ? `<p class="note">${esc(it.n)}</p>` : ''}</div></li>`;
  }
  html += '</ol></section>';
  toc.insertAdjacentHTML('beforeend', `<a href="#${sec.id}">${sec.title}</a>`);
}

// electrical + plumbing points, grouped by room
html += '<section id="points"><h2>Всички ел. и ВиК точки</h2><p class="lead">Генерирано от 3D модела – номерата съвпадат с етикетите в сайта. Височините са от готовия под.</p>';
for (const room of ROOMS) {
  const pts = ELECTRIC.filter((p) => p.room === room);
  if (!pts.length) continue;
  html += `<h3>${ROOM_NAME[room] || room}</h3><div class="table-wrap"><table><thead><tr><th></th><th>№</th><th>Вид</th><th>Описание</th><th>Височина</th></tr></thead><tbody>`;
  for (const p of pts) {
    const key = `pt-${p.id}-${p.variant || ''}`;
    const h = p.ceil ? 'таван' : p.floor ? 'в пода' : `${p.h} см`;
    const notes = [p.note, VARIANT[p.variant]].filter(Boolean).map((n) => `<span class="note">${esc(n)}</span>`).join('');
    html += `<tr class="${store.get(key) ? 'is-done' : ''}"><td>${check(key)}</td><td><span class="tag t-${p.t}">${p.id}</span></td><td>${TYPE[p.t] || p.t}</td><td>${esc(p.bg)}${notes}</td><td class="h">${h}</td></tr>`;
  }
  html += '</tbody></table></div>';
}
html += '</section>';
toc.insertAdjacentHTML('beforeend', '<a href="#points">Ел. и ВиК точки</a>');
main.innerHTML = html;

main.addEventListener('change', (e) => {
  const el = e.target;
  if (!el.classList.contains('done')) return;
  store.set(el.dataset.key, el.checked);
  el.closest('li, tr').classList.toggle('is-done', el.checked);
  updateCount();
});
function updateCount() {
  const all = main.querySelectorAll('.done');
  const done = [...all].filter((c) => c.checked).length;
  document.getElementById('count').textContent = `${done} от ${all.length} договорени`;
}
updateCount();
document.getElementById('print').addEventListener('click', () => window.print());
